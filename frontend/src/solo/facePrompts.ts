// Какую грань показывать на каждом шаге съёмки.
//
// Живая жалоба 2026-08-24: «Снять грань 3/6» не говорит НИЧЕГО о том, какую
// именно грань нести к рамке. Человек показывает наугад, попадает дважды одной
// и той же, раскладка шести съёмок по шести цветам не сходится — и экран
// отвечает про доверие к ячейкам, хотя ошибка была в порядке показа.
//
// Порядок СОВЕТ, а не требование. Продуктовый путь узнаёт грань по центру
// (`cubeGrid.assignFacesByCenter`) и принимает любой порядок; строгий порядок
// нужен только харнессу гейта, где позиции наклеек сравниваются с эталоном.
// Поэтому подсказка ведёт по фиксированному кругу, но чтение не сломается,
// если показать иначе — важно лишь не показать одну грань дважды.
//
// Две формулировки, и разница не косметическая. На СОБРАННОМ кубике (калибровка
// и подтверждение сборки) грань одноцветная, и «покажи белую грань» — точное
// указание. На СКРАМБЛИРОВАННОМ (сверка разброса) одноцветной грани не
// существует вовсе: у каждой все девять наклеек разные, и единственное, что
// делает грань «той самой», — её центр, который не двигает ни один ход. Тем же
// различием когда-то чинили подсказки харнесса (`accuracy/captureHints.ts`).

/** Порядок обхода — тот же URFDLB, что и везде в проекте. */
export const SOLO_FACE_ORDER = ["U", "R", "F", "D", "L", "B"] as const;

export type SoloFace = (typeof SOLO_FACE_ORDER)[number];

/** Собранный кубик: грань одноцветная, называем цветом. */
const SOLVED_PROMPT: Record<SoloFace, string> = {
  U: "Покажи БЕЛУЮ грань",
  R: "Покажи КРАСНУЮ грань",
  F: "Покажи ЗЕЛЁНУЮ грань",
  D: "Покажи ЖЁЛТУЮ грань",
  L: "Покажи ОРАНЖЕВУЮ грань",
  B: "Покажи СИНЮЮ грань",
};

/** Скрамблированный кубик: одноцветных граней нет, называем центром. */
const SCRAMBLED_PROMPT: Record<SoloFace, string> = {
  U: "Покажи грань с БЕЛЫМ центром",
  R: "Покажи грань с КРАСНЫМ центром",
  F: "Покажи грань с ЗЕЛЁНЫМ центром",
  D: "Покажи грань с ЖЁЛТЫМ центром",
  L: "Покажи грань с ОРАНЖЕВЫМ центром",
  B: "Покажи грань с СИНИМ центром",
};

/**
 * Ключ перевода для шага `step` (0-based). За шестым шагом — пусто: показывать
 * больше нечего, а придумывать седьмую грань нельзя.
 *
 * @param solved собран ли кубик в этой фазе (калибровка и подтверждение — да,
 *               сверка разброса — нет).
 */
export function facePrompt(step: number, solved: boolean): string | null {
  if (!Number.isInteger(step) || step < 0 || step >= SOLO_FACE_ORDER.length) return null;
  const face = SOLO_FACE_ORDER[step];
  return solved ? SOLVED_PROMPT[face] : SCRAMBLED_PROMPT[face];
}
