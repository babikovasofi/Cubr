// Единая точка правды для "@ник" (see backend/app/schemas/user.py: `handle`
// хранится БЕЗ ведущей «собаки», "@" — только оформление при показе). Раньше
// это писалось по месту в паре компонентов и неизбежно бы разъехалось —
// поэтому один хелпер, а не пять копий.

/** Отображение: голый ник -> «@ник». Вызывать только на непустом значении —
 *  для `null`/незаданного ника решение о тексте принимает вызывающий код
 *  (см. ProfilePage), т.к. приемлемый текст-заглушка зависит от контекста. */
export function formatHandle(handle: string): string {
  return `@${handle}`;
}

/** Ввод/сохранение: если человек всё же набрал «@ник» — молча срезаем ведущую
 *  собаку. В поле ввода и в запросах на сервер уезжает всегда голый ник. */
export function stripHandlePrefix(raw: string): string {
  return raw.startsWith("@") ? raw.slice(1) : raw;
}
