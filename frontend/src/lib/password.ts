// Единственное место на фронте, где живёт минимальная длина пароля.
// Значение обязано совпадать с `MIN_LENGTH` в
// `backend/app/services/password_policy.py` — расхождение (фронт говорил 8,
// сервер требовал 10) делало регистрацию непроходимой: человек вводил 9
// символов, получал «минимум 8» и не понимал, что не так.
export const PASSWORD_MIN_LENGTH = 10;

/** Подсказка под полем пароля — правила видны ДО отправки формы. */
export const PASSWORD_HINT = `Минимум ${PASSWORD_MIN_LENGTH} символов. Не почта и не ник, не из списка самых частых паролей.`;
