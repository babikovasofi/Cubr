// Множественное число для строк-ключей (см. i18n/t.ts: ключ = русская фраза).
//
// Английский обошёлся бы одним `n === 1`, русский — тремя формами, и склоняется
// не только существительное, но и глагол («1 участник не финишировал» против
// «2 участника не финишировали»). Поэтому выбираем не слово, а ФРАЗУ целиком:
// она и есть ключ перевода, а словарь схлопнет три русские формы в две
// английские. Собирать фразу из переведённых кусков нельзя — порядок слов и
// согласование в языках разные.

/** Русская форма по числу: 0 — «1 день», 1 — «2 дня», 2 — «5 дней». */
export function pluralFormRu(n: number): 0 | 1 | 2 {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return 0;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 1;
  return 2;
}

/** Русская фраза по числу — её же скармливают `t()` как ключ. */
export function pluralRu(n: number, forms: readonly [string, string, string]): string {
  return forms[pluralFormRu(n)];
}
