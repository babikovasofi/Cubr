// Решение против мигания: если сохранённый/браузерный язык — `en`, main.tsx
// ждёт эту функцию ДО первого рендера, иначе первый экран мигнёт русским и тут
// же переключится на английский. Для большинства (русский — дефолт) она не
// ждёт ничего. Провал чанка (см. t.ts) не блокирует загрузку навсегда —
// приложение рендерится с тем, что есть (русский, та же деградация, что и у
// RouteErrorBoundary).
//
// Вынесена из main.tsx в отдельный модуль без побочных эффектов при импорте:
// сам main.tsx на верхнем уровне создаёт React-root и рендерит дерево — импорт
// этого файла напрямую в тестах небезопасен.

import { initialLang } from "../store/langStore";
import { loadEnDict } from "./t";

export async function loadInitialDict(): Promise<void> {
  if (initialLang() === "en") {
    await loadEnDict().catch(() => undefined);
  }
}
